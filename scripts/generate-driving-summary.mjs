/**
 * Generate src/lib/driving/summary.generated.ts - a LIGHT list of jurisdictions
 * for client components that only need to link to them.
 *
 * WHY THIS EXISTS. jurisdictions.ts pulls in every question of every bank, and
 * excerpts.ts pulls in every handbook quote and snippet manifest. Importing
 * either from a "use client" component drags the entire driving corpus into the
 * browser bundle. Measured at 29 jurisdictions: one 6.7 MB chunk, loaded by the
 * HOME PAGE and by every driving page, so a visitor reading about Minnesota
 * also downloaded Quebec, Alabama and everything else. That grows with every
 * jurisdiction added, on a site whose audience is teenagers on phones.
 *
 * So: server components may import the full registry freely (their data stays
 * on the server unless passed as props), and client components that need the
 * whole LIST import this file instead. It carries no questions and no quotes.
 *
 * Run from prebuild. Regenerate after adding a jurisdiction; the driving
 * validator has no view of this file, so a stale copy shows up as a missing
 * card on the home page rather than as an error.
 */
import { writeFileSync } from "node:fs";
import { JURISDICTIONS } from "../src/lib/driving/jurisdictions.ts";

const rows = JURISDICTIONS.map((j) => ({
  slug: j.slug,
  name: j.name,
  code: j.code,
  country: j.country,
  licenceName: j.licenceName,
  intro: j.intro,
  contentDate: j.contentDate,
  setCount: j.sets.length,
  questionCount: j.sets.reduce((n, s) => n + s.questions.length, 0),
}));

const file = `// GENERATED by scripts/generate-driving-summary.mjs - do not edit by hand.
//
// A light index of the driving jurisdictions: no questions, no handbook quotes.
// Client components import THIS rather than jurisdictions.ts, which would drag
// the whole corpus into the browser bundle. See the generator for the measured
// reason why.

export interface JurisdictionSummary {
  slug: string;
  name: string;
  code: string;
  country: "CA" | "US";
  licenceName: string;
  intro: string;
  contentDate: string;
  setCount: number;
  questionCount: number;
}

export const JURISDICTION_SUMMARIES: JurisdictionSummary[] = ${JSON.stringify(rows, null, 2)};

/** Total practice questions across every jurisdiction. */
export const TOTAL_DRIVING_QUESTIONS = ${rows.reduce((n, r) => n + r.questionCount, 0)};
`;

writeFileSync("src/lib/driving/summary.generated.ts", file, "utf8");
console.log(
  `src/lib/driving/summary.generated.ts: ${rows.length} jurisdictions, ${rows.reduce((n, r) => n + r.questionCount, 0)} questions`
);
