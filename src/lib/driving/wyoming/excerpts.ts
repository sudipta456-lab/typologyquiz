// Short verbatim excerpts behind the Wyoming bank.
//
// Sources, and why there are three of them:
//
//  - "Rules of the Road", the State of Wyoming Driver License Manual, 2021
//    edition, produced by the WYDOT Driver Services Program Public Affairs
//    Office in August 2021. This is the book WYDOT writes the knowledge test
//    from - the manual says so itself: "Questions are taken from the
//    information in this manual." Most of what is quoted below comes from it.
//  - Wyoming Statutes Title 31 (Motor Vehicles), published by the Wyoming
//    Legislature at wyoleg.gov. The manual is explicit that it is not the law:
//    "The language of the Wyoming Motor Vehicle Law is not used in this manual,
//    which therefore cannot be used as an actual expression of the law." It
//    also leaves out numbers the test still expects - every parking distance
//    except the fire hydrant, the railroad-crossing stop distance, the
//    liability minimums, the texting fine, the statutory speed table for
//    unpaved and non-interstate roads. Those come from Title 31.
//  - Four dot.state.wy.us Driver Services pages (Learner Permits, Testing,
//    Driver License, Frequently Asked Questions). The manual predates the
//    current fee schedule and says nothing about the 10-day permit-holding
//    rule that gates every Wyoming teen's licence, and those pages carry both.
//
// All four sources were fetched directly on 2026-09-07; none of them blocked
// an automated client, so no archive capture was needed. The manual PDF and
// the Title 31 PDF were both checked for a broken font map before anything was
// quoted from them: the manual produced exactly one suspect token across 98
// pages ("SL0W", which is a stylised graphic caption, not prose), and Title 31
// produced none across 542 pages.
//
// Every quote was located mechanically in the fetched source and checked as an
// exact substring before it was written here. Nothing is paraphrased. The only
// normalisations applied to the extracted text - and to nothing else - are the
// four the pipeline permits: curly quotes, en dashes and em dashes fold to
// ASCII; runs of whitespace, including the line breaks and soft hyphens the
// PDF inserts mid-word, collapse to single spaces; the section symbol is
// spelled out as "Section"; and where a source states a rule as a stem
// followed by a bulleted list, the items run together in the order they
// appear. No words are changed, dropped or reordered. The sources' own slips
// stand as they are, including the manual's "Slippery roads reduce your the
// tires' grip", "Others situations may require a driver", "If you with to
// specify a medical condition" and "for a period of two year", because a quote
// that has been tidied up is no longer a quote.

